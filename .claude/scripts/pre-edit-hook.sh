#!/usr/bin/env bash
# PreToolUse: block edits to generated or machine-owned paths.
set -u

f=$(jq -r '.tool_input.file_path // empty')
rel=${f#"$CLAUDE_PROJECT_DIR"/}
case "$rel" in
  ios/*|android/*)
    echo "BLOCK: $rel is generated by expo prebuild. Change app.json or a config plugin instead." >&2
    exit 2 ;;
  package-lock.json)
    echo "BLOCK: package-lock.json is written by npm. Run npm install --legacy-peer-deps instead." >&2
    exit 2 ;;
  supabase/.temp/*)
    echo "BLOCK: supabase/.temp is CLI state. Do not hand-edit it." >&2
    exit 2 ;;
esac
exit 0
